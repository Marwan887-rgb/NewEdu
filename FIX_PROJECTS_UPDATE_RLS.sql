-- ════════════════════════════════════════════════════════════
-- إصلاح سياسة UPDATE لجدول المشاريع - Projects Update Fix
-- ════════════════════════════════════════════════════════════
-- المشكلة: لا يمكن تحديث حالة المشاريع من "معلق" إلى "معتمد"
-- السبب: لا توجد سياسة UPDATE في RLS لجدول project_submissions
-- الحل: إضافة سياسة UPDATE للسماح بالتحديث
-- ════════════════════════════════════════════════════════════
-- ⚠️ مهم: هذا السكريبت لا يحذف أي ملفات أو بيانات للطلاب
-- ════════════════════════════════════════════════════════════

BEGIN;

SELECT '════════════════════════════════════════════' as msg;
SELECT '🔧 بدء إصلاح سياسة UPDATE لجدول المشاريع...' as msg;
SELECT '════════════════════════════════════════════' as msg;

-- ════════════════════════════════════════════════════════════
-- 1. حذف السياسة القديمة (إن وجدت)
-- ════════════════════════════════════════════════════════════
DROP POLICY IF EXISTS "project_submissions_update" ON project_submissions;
DROP POLICY IF EXISTS "project_submissions_update_all" ON project_submissions;

SELECT '✅ تم حذف السياسات القديمة (إن وجدت)' as msg;

-- ════════════════════════════════════════════════════════════
-- 2. إنشاء سياسة UPDATE جديدة
-- ════════════════════════════════════════════════════════════
CREATE POLICY "project_submissions_update_all" 
  ON project_submissions
  FOR UPDATE
  TO anon, authenticated
  USING (true)
  WITH CHECK (true);

SELECT '✅ تم إنشاء سياسة UPDATE للمشاريع' as msg;

-- ════════════════════════════════════════════════════════════
-- 3. التأكد من تفعيل RLS على الجدول
-- ════════════════════════════════════════════════════════════
ALTER TABLE project_submissions ENABLE ROW LEVEL SECURITY;

SELECT '✅ تم تفعيل RLS على جدول project_submissions' as msg;

COMMIT;

-- ════════════════════════════════════════════════════════════
-- التحقق النهائي
-- ════════════════════════════════════════════════════════════
SELECT '════════════════════════════════════════════' as msg;
SELECT '🎉 اكتمل الإصلاح بنجاح!' as msg;
SELECT '════════════════════════════════════════════' as msg;

SELECT '📊 السياسات الموجودة حالياً:' as msg;
SELECT policyname, cmd, roles
FROM pg_policies 
WHERE tablename = 'project_submissions'
ORDER BY cmd;

SELECT '════════════════════════════════════════════' as msg;
SELECT '✅ جميع ملفات الطلاب محفوظة وآمنة' as msg;
SELECT '✅ يمكنك الآن اعتماد المشاريع بدون مشاكل' as msg;
SELECT '════════════════════════════════════════════' as msg;
