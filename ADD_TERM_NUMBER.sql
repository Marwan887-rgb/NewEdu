BEGIN;

SELECT '════════════════════════════════════════════' as msg;
SELECT '🔧 بدء تحديث قاعدة البيانات...' as msg;
SELECT '════════════════════════════════════════════' as msg;

-- ════════════════════════════════════════════════════════════
-- 1. إضافة حقل term_number
-- ════════════════════════════════════════════════════════════

-- التحقق إذا كان الحقل موجود مسبقاً
DO $$ 
BEGIN
    IF NOT EXISTS (
        SELECT 1 
        FROM information_schema.columns 
        WHERE table_name='lessons' 
        AND column_name='term_number'
    ) THEN
        ALTER TABLE lessons ADD COLUMN term_number INTEGER;
        RAISE NOTICE '✅ تمت إضافة حقل term_number';
    ELSE
        RAISE NOTICE '⚠️ حقل term_number موجود مسبقاً';
    END IF;
END $$;

SELECT '✅ تم إضافة حقل term_number' as msg;

-- ════════════════════════════════════════════════════════════
-- 2. تحديث الفترة الأولى (أسابيع 1-8)
-- ════════════════════════════════════════════════════════════

UPDATE lessons 
SET term_number = 1 
WHERE week_number BETWEEN 1 AND 8;

SELECT '✅ تم تحديث الفترة الأولى (أسابيع 1-8)' as msg;

-- ════════════════════════════════════════════════════════════
-- 3. تحديث الفترة الثانية (أسابيع 9-16)
-- ════════════════════════════════════════════════════════════

UPDATE lessons 
SET term_number = 2 
WHERE week_number BETWEEN 9 AND 16;

SELECT '✅ تم تحديث الفترة الثانية (أسابيع 9-16)' as msg;

-- ════════════════════════════════════════════════════════════
-- 4. التحقق من النتائج
-- ════════════════════════════════════════════════════════════

SELECT '════════════════════════════════════════════' as msg;
SELECT '📊 ملخص التحديثات:' as msg;
SELECT '════════════════════════════════════════════' as msg;

-- عرض توزيع الدروس حسب الفترات
SELECT 
  term_number as "الفترة",
  COUNT(*) as "عدد الدروس",
  MIN(week_number) as "من أسبوع",
  MAX(week_number) as "إلى أسبوع"
FROM lessons
WHERE term_number IS NOT NULL
GROUP BY term_number
ORDER BY term_number;

SELECT '─────────────────────────────────────────────' as msg;

-- عرض تفاصيل كل درس
SELECT 
  id as "ID",
  title as "العنوان",
  week_number as "الأسبوع",
  term_number as "الفترة",
  type as "النوع"
FROM lessons
ORDER BY week_number, id;

SELECT '════════════════════════════════════════════' as msg;
SELECT '✅ تم تحديث قاعدة البيانات بنجاح!' as msg;
SELECT '════════════════════════════════════════════' as msg;

